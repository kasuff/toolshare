import { Link, useNavigate, useSearchParams } from 'react-router-dom';
import { useRef, useState } from 'react';
import { DetailTopBar } from './DetailTopBar';
import { ConfirmDialog } from './ConfirmDialog';
import { DateInput } from './DateInput';
import { RatingsSection } from './RatingsSection';
import { ReportFormPanel } from './ReportFormPanel';
import { SystemRulesInfo } from './SystemRulesInfo';
import { DEFAULT_PLACEHOLDER_IMAGE } from '@toolshare/shared';
import { useToast } from '../hooks/useToast';
import {
  useCreateWorkshopBooking,
  useCreateWorkshopTimeslot,
  useDeleteWorkshop,
  useWorkshopRatings,
} from '../hooks/queries/workshops.queries';
import { useCreateReport } from '../hooks/queries/reports.mutations';
import { isDateRangeAvailable } from '@toolshare/shared';
import { pluralize } from '@toolshare/shared';
import { useModalFocus } from '../hooks/useModalFocus';
import type {
  Tool,
  User,
  Workshop,
  WorkshopBookedRange,
  WorkshopSlot,
} from '@toolshare/shared';
import { usePageAuth } from '../hooks/usePageAuth';

import {
  type BookingDraft,
  getDefaultBookingDraft,
  combineLocalDateTimeToIso,
  extrasByValue,
  toolCategoryByValue,
  getWorkshopExtras,
  isAutoGeneratedWorkshopDescription,
  getInitials,
  getWorkshopCalendarDays,
} from '../utils/workshopHelpers';

export type WorkshopListItem = {
  workshop: Workshop;
  slots: WorkshopSlot[];
  bookedRanges: WorkshopBookedRange[];
  tools: Array<Tool & { selectable: boolean }>;
};

type Props = {
  selectedWorkshop: WorkshopListItem;
  selectedWorkshopOwnerOfferCount: number;
  onClose: () => void;
  onBlockSuccess: (
    workshopId: string,
    refreshed: { workshop: Workshop; slots: WorkshopSlot[] }
  ) => void;
  onDeleteSuccess: () => void;
  currentUser?: User;
  token?: string | null;
};

export function WorkshopDetailView({
  selectedWorkshop,
  selectedWorkshopOwnerOfferCount,
  onClose,
  onBlockSuccess,
  onDeleteSuccess,
  currentUser: propUser,
  token: propToken,
}: Props) {
  const { currentUser, token } = usePageAuth(propUser, propToken);
  const { pushToast } = useToast();
  const navigate = useNavigate();
  const [searchParams] = useSearchParams();
  const workshopId = selectedWorkshop.workshop.id;
  const { data: workshopRatings = [] } = useWorkshopRatings(workshopId);
  const createWorkshopBooking = useCreateWorkshopBooking(token ?? '');
  const createWorkshopTimeslot = useCreateWorkshopTimeslot(token ?? '');
  const deleteWorkshop = useDeleteWorkshop(token ?? '');
  const createReport = useCreateReport(token ?? '');

  const imageViewerRef = useRef<HTMLDivElement>(null);
  const imageViewerCloseRef = useRef<HTMLButtonElement>(null);


  const [bookingDraft, setBookingDraft] = useState<BookingDraft>(getDefaultBookingDraft());
  const [isSelectingRangeEnd, setIsSelectingRangeEnd] = useState(false);
  const [calendarMonthOffset, setCalendarMonthOffset] = useState(0);

  const [activeImageIndex, setActiveImageIndex] = useState<number | null>(null);

  const [showReportForm, setShowReportForm] = useState(false);
  const [reportReason, setReportReason] = useState('');
  const [reportDetails, setReportDetails] = useState('');
  const [isReporting, setIsReporting] = useState(false);

  const [showDeleteDialog, setShowDeleteDialog] = useState(false);
  const [isDeleting, setIsDeleting] = useState(false);



  const closeWorkshop = onClose;

  const closeReportForm = () => {
    setShowReportForm(false);
    setReportReason('');
    setReportDetails('');
  };

  const showPreviousImage = () => {
    setActiveImageIndex((current) => {
      if (current === null) return null;
      return (current - 1 + selectedWorkshopImages.length) % selectedWorkshopImages.length;
    });
  };

  const showNextImage = () => {
    setActiveImageIndex((current) => {
      if (current === null) return null;
      return (current + 1) % selectedWorkshopImages.length;
    });
  };

  const openWorkshopImage = (index: number) => {
    if (selectedWorkshopImages[index] === DEFAULT_PLACEHOLDER_IMAGE) {
      pushToast('Keine Bilder vorhanden.', 'info');
      return;
    }
    setActiveImageIndex(index);
  };

  const closeImageViewer = () => setActiveImageIndex(null);
  useModalFocus(imageViewerRef, closeImageViewer, imageViewerCloseRef, activeImageIndex !== null);

  const selectWorkshopCalendarDate = (dateKey: string) => {
    if (!isSelectingRangeEnd || dateKey < bookingDraft.startDate) {
      setBookingDraft((prev) => ({ ...prev, startDate: dateKey, endDate: dateKey }));
      setIsSelectingRangeEnd(true);
      return;
    }

    if (
      !isDateRangeAvailable(
        bookingDraft.startDate,
        dateKey,
        selectedWorkshop.slots,
        selectedWorkshop.bookedRanges
      )
    ) {
      pushToast('Der gewählte Zeitraum enthält blockierte oder bereits gebuchte Tage.', 'error');
      return;
    }

    setBookingDraft((prev) => ({ ...prev, endDate: dateKey }));
    setIsSelectingRangeEnd(false);
  };

  const bookWorkshop = async (workshopId: string) => {
    if (!token) {
      pushToast('Zum Buchen bitte anmelden.', 'info');
      navigate('/auth', {
        state: { redirectHint: 'Bitte melde dich an, um eine Werkstatt zu buchen.' },
      });
      return;
    }

    const startIso = combineLocalDateTimeToIso(bookingDraft.startDate, bookingDraft.startTime);
    const endIso = combineLocalDateTimeToIso(bookingDraft.endDate, bookingDraft.endTime);
    if (!startIso || !endIso) return;
    if (new Date(startIso) < new Date()) {
      pushToast('Der Startzeitpunkt darf nicht in der Vergangenheit liegen.', 'error');
      return;
    }
    if (new Date(endIso) <= new Date(startIso)) {
      pushToast('Das Ende muss nach dem Start liegen.', 'error');
      return;
    }

    if (
      !isDateRangeAvailable(
        bookingDraft.startDate,
        bookingDraft.endDate,
        selectedWorkshop.slots,
        selectedWorkshop.bookedRanges
      )
    ) {
      pushToast('Der gewählte Zeitraum ist blockiert oder bereits gebucht.', 'error');
      return;
    }

    try {
      const createdBooking = await createWorkshopBooking.mutateAsync({
        workshopId,
        startIso,
        endIso,
        workshopToolIds: []
      });
      pushToast('Werkstattbuchung erstellt.', 'success');
      setBookingDraft(getDefaultBookingDraft());
      navigate('/inbox', { state: { bookingId: createdBooking.id } });
    } catch (error) {
      pushToast(error instanceof Error ? error.message : 'Buchung fehlgeschlagen.', 'error');
    }
  };

  const blockWorkshopForOwnUse = async (workshopId: string) => {
    if (!token) return;
    const startIso = combineLocalDateTimeToIso(bookingDraft.startDate, bookingDraft.startTime);
    const endIso = combineLocalDateTimeToIso(bookingDraft.endDate, bookingDraft.endTime);
    if (!startIso || !endIso) return;
    if (new Date(startIso) < new Date()) {
      pushToast('Der Startzeitpunkt darf nicht in der Vergangenheit liegen.', 'error');
      return;
    }
    if (new Date(endIso) <= new Date(startIso)) {
      pushToast('Das Ende muss nach dem Beginn liegen.', 'error');
      return;
    }
    try {
      const refreshed = await createWorkshopTimeslot.mutateAsync({
        workshopId,
        startIso,
        endIso,
        blockedByOwner: true
      });
      onBlockSuccess(workshopId, refreshed);
      pushToast('Werkstatt wurde für deinen Eigenbedarf blockiert.', 'success');
    } catch (error) {
      pushToast(
        error instanceof Error ? error.message : 'Werkstatt konnte nicht blockiert werden.',
        'error'
      );
    }
  };

  const deleteSelectedWorkshop = async () => {
    if (!token) return;
    setIsDeleting(true);
    try {
      await deleteWorkshop.mutateAsync(selectedWorkshop.workshop.id);
      pushToast('Werkstatt endgültig gelöscht.', 'success');
      setShowDeleteDialog(false);
      onDeleteSuccess();
    } catch (error) {
      pushToast(
        error instanceof Error ? error.message : 'Werkstatt konnte nicht gelöscht werden.',
        'error'
      );
      setIsDeleting(false);
    }
  };

  const openReportForm = () => {
    if (!token) {
      navigate('/auth', {
        state: { redirectHint: 'Bitte melde dich an, um ein Angebot zu melden.' },
      });
      return;
    }
    setShowReportForm(true);
  };

  const reportWorkshop = async (workshopId: string) => {
    if (reportReason.trim().length < 5) return;
    setIsReporting(true);
    try {
      await createReport.mutateAsync({
        targetType: 'WORKSHOP',
        targetId: workshopId,
        reason: reportReason.trim(),
        details: reportDetails.trim() || undefined,
      });
      closeReportForm();
      pushToast('Werkstatt wurde gemeldet.', 'success');
    } catch (error) {
      pushToast(
        error instanceof Error ? error.message : 'Meldung konnte nicht gesendet werden.',
        'error'
      );
    } finally {
      setIsReporting(false);
    }
  };

  const selectedWorkshopDraftAvailable = isDateRangeAvailable(
    bookingDraft.startDate,
    bookingDraft.endDate,
    selectedWorkshop.slots,
    selectedWorkshop.bookedRanges
  );
  const selectedWorkshopIsOwn = Boolean(currentUser?.id === selectedWorkshop.workshop.ownerId);
  const selectedWorkshopManageMode = selectedWorkshopIsOwn && searchParams.get('manage') === '1';
  const selectedWorkshopImages =
    selectedWorkshop.workshop.imageUrls.length > 0
      ? selectedWorkshop.workshop.imageUrls
      : [DEFAULT_PLACEHOLDER_IMAGE];
  const selectedWorkshopExtras = getWorkshopExtras(selectedWorkshop.workshop);

  const currentCalendarMonth = new Date();
  currentCalendarMonth.setDate(1);
  currentCalendarMonth.setMonth(currentCalendarMonth.getMonth() + calendarMonthOffset);
  const selectedWorkshopCalendarMonths = [0, 1].map((monthIndex) => {
    const monthDate = new Date(currentCalendarMonth);
    monthDate.setMonth(monthDate.getMonth() + monthIndex);
    return {
      key: `${monthDate.getFullYear()}-${monthDate.getMonth()}`,
      label: new Intl.DateTimeFormat('de-DE', { month: 'long', year: 'numeric' }).format(monthDate),
      days: getWorkshopCalendarDays(
        monthDate,
        selectedWorkshop.slots,
        selectedWorkshop.bookedRanges
      ),
    };
  });

  const selectedWorkshopDraft = bookingDraft;

  return (
    <div className="workshop-detail-page" role="region" aria-label={selectedWorkshop.workshop.name}>
      <div className="workshop-detail-page-content">
        <div className="workshop-modal-toolbar">
          <DetailTopBar onBack={closeWorkshop}>
            <button type="button" className="detail-report-trigger" onClick={openReportForm}>
              Werkstatt melden
            </button>
          </DetailTopBar>
        </div>

        {showReportForm && (
          <ReportFormPanel
            title="Werkstatt melden"
            hint="Wenn Regeln verletzt werden, melde diese Werkstatt der Moderation."
            reason={reportReason}
            details={reportDetails}
            isSubmitting={isReporting}
            submitLabel="Werkstatt melden"
            onReasonChange={setReportReason}
            onDetailsChange={setReportDetails}
            onSubmit={() => void reportWorkshop(selectedWorkshop.workshop.id)}
            onCancel={closeReportForm}
          />
        )}

        <div className="workshop-detail-gallery">
          <div
            className={`workshop-detail-gallery-grid ${selectedWorkshopImages.length === 1 ? 'single' : ''}`.trim()}
          >
            <button
              type="button"
              className="workshop-detail-image-main"
              onClick={() => openWorkshopImage(0)}
              aria-label={
                selectedWorkshopImages[0] === DEFAULT_PLACEHOLDER_IMAGE
                  ? 'Keine Bilder vorhanden'
                  : `${selectedWorkshop.workshop.name} vergrößern`
              }
            >
              <img src={selectedWorkshopImages[0]} alt={selectedWorkshop.workshop.name} />
            </button>
            {selectedWorkshopImages.length > 1 && (
              <div className="workshop-detail-image-stack">
                {selectedWorkshopImages.slice(1, 3).map((imageUrl, index) => (
                  <button
                    type="button"
                    key={`${imageUrl}-${index}`}
                    className="workshop-detail-image-thumb"
                    onClick={() => openWorkshopImage(index + 1)}
                    aria-label={
                      imageUrl === DEFAULT_PLACEHOLDER_IMAGE
                        ? 'Keine Bilder vorhanden'
                        : `Bild ${index + 2} von ${selectedWorkshop.workshop.name} vergrößern`
                    }
                  >
                    <img src={imageUrl} alt={`${selectedWorkshop.workshop.name} ${index + 2}`} />
                  </button>
                ))}
              </div>
            )}
          </div>
        </div>

        <div className="workshop-detail-layout">
          <div className="workshop-detail-main">
            <header className="workshop-detail-header">
              <h2>{selectedWorkshop.workshop.name}</h2>
              <div className="workshop-modal-meta">
                <span className="status-pill neutral">
                  {selectedWorkshop.workshop.maxCapacity} Plätze
                </span>
                <span className="status-pill neutral">
                  {pluralize(selectedWorkshop.slots.length, 'Zeitfenster', 'Zeitfenster')}
                </span>
                {currentUser && selectedWorkshop.workshop.ownerId === currentUser.id && (
                  <span className="status-pill warning">Eigene Werkstatt</span>
                )}
              </div>
            </header>

            {selectedWorkshop.tools.length > 0 && (
              <section className="workshop-detail-section">
                <h3>Werkzeuge</h3>
                <ul className="workshop-detail-list">
                  {selectedWorkshop.tools.map((tool) => (
                    <li key={tool.id} className={tool.selectable ? '' : 'is-muted'}>
                      {tool.name}
                      {!tool.selectable && <span>Ausgeliehen</span>}
                    </li>
                  ))}
                </ul>
              </section>
            )}

            <section className="workshop-detail-section">
              <h3>Details</h3>
              <p>
                {isAutoGeneratedWorkshopDescription(selectedWorkshop.workshop)
                  ? 'Für diese Werkstatt wurde keine zusätzliche Beschreibung hinterlegt.'
                  : selectedWorkshop.workshop.description}
              </p>
            </section>

            {selectedWorkshopExtras.length > 0 && (
              <section className="workshop-detail-section">
                <h3>Extras</h3>
                <div className="workshop-detail-chip-grid">
                  {selectedWorkshopExtras.map((extraValue) => {
                    const extra = extrasByValue.get(extraValue);
                    return (
                      <span key={extraValue} className="workshop-detail-chip">
                        <span className="material-symbols-outlined">
                          {extra?.icon ?? 'construction'}
                        </span>
                        <span>{extra?.label ?? extraValue}</span>
                      </span>
                    );
                  })}
                </div>
              </section>
            )}

            <section className="workshop-detail-section">
              <h3>Adresse</h3>
              <p>{selectedWorkshop.workshop.location}</p>
            </section>

            <section className="workshop-detail-section">
              <h3>Anbieter</h3>
              <div className="workshop-detail-provider">
                <span className="ds-workshop-card-avatar">
                  {getInitials(selectedWorkshop.workshop.ownerName ?? 'Unbekannt')}
                </span>
                <div>
                  <strong>{selectedWorkshop.workshop.ownerName ?? 'Unbekannt'}</strong>
                  <span>{pluralize(selectedWorkshopOwnerOfferCount, 'Angebot', 'Angebote')}</span>
                </div>
              </div>
            </section>

            <section className="workshop-detail-section">
              <div className="workshop-calendar-toolbar">
                <h3>Verfügbare Tage</h3>
                <div className="workshop-calendar-navigation">
                  <button
                    type="button"
                    aria-label="Vorherige Monate"
                    title="Vorherige Monate"
                    disabled={calendarMonthOffset === 0}
                    onClick={() => setCalendarMonthOffset((offset) => Math.max(0, offset - 1))}
                  >
                    <span className="material-symbols-outlined">chevron_left</span>
                  </button>
                  <button
                    type="button"
                    aria-label="Nächste Monate"
                    title="Nächste Monate"
                    onClick={() => setCalendarMonthOffset((offset) => offset + 1)}
                  >
                    <span className="material-symbols-outlined">chevron_right</span>
                  </button>
                </div>
              </div>
              <p className="workshop-calendar-instruction">
                {isSelectingRangeEnd
                  ? 'Wähle jetzt das Ende des Zeitraums.'
                  : 'Wähle den ersten Tag des Zeitraums.'}
              </p>
              <div className="workshop-calendar-months">
                {selectedWorkshopCalendarMonths.map((month) => (
                  <div key={month.key} className="workshop-calendar-month">
                    <h4>{month.label}</h4>
                    <div
                      className="workshop-calendar"
                      aria-label={`Verfügbare Tage im ${month.label}`}
                    >
                      {['Mo', 'Di', 'Mi', 'Do', 'Fr', 'Sa', 'So'].map((weekday) => (
                        <span key={weekday} className="workshop-calendar-weekday">
                          {weekday}
                        </span>
                      ))}
                      {month.days.map((day) => {
                        const dateKey = day.dateKey ?? '';
                        const isRangeStart = dateKey === selectedWorkshopDraft?.startDate;
                        const isRangeEnd = dateKey === selectedWorkshopDraft?.endDate;
                        const isInRange = Boolean(
                          dateKey &&
                          selectedWorkshopDraft &&
                          dateKey >= selectedWorkshopDraft.startDate &&
                          dateKey <= selectedWorkshopDraft.endDate
                        );
                        return day.day === null ? (
                          <span key={day.key} className="workshop-calendar-day empty" />
                        ) : (
                          <button
                            key={day.key}
                            type="button"
                            className={`workshop-calendar-day ${day.available ? 'available' : 'unavailable'} ${
                              isInRange ? 'in-range' : ''
                            } ${isRangeStart ? 'range-start' : ''} ${isRangeEnd ? 'range-end' : ''}`.trim()}
                            disabled={!day.available}
                            onClick={() => selectWorkshopCalendarDate(dateKey)}
                          >
                            {day.day}
                          </button>
                        );
                      })}
                    </div>
                  </div>
                ))}
              </div>
              <div className="workshop-calendar-legend">
                <span>
                  <i className="available" /> Verfügbar
                </span>
                <span>
                  <i className="unavailable" /> Blockiert / gebucht
                </span>
              </div>
            </section>

            <RatingsSection
              ratings={workshopRatings}
              token={token ?? undefined}
              canReport={!selectedWorkshopIsOwn}
            />
          </div>

          {
            <aside className="playtomic-booking-panel workshop-detail-booking">
              <h2>
                {selectedWorkshopIsOwn
                  ? 'Werkstatt für Eigenbedarf blockieren'
                  : 'Werkstatt buchen'}
              </h2>

              <div className="booking-section">
                <div className="booking-section-title">
                  <span />
                  <strong>
                    {selectedWorkshopIsOwn ? 'Beginn des Eigenbedarfs' : 'Abholdaten'}
                  </strong>
                </div>
                <div className="booking-fields-row">
                  <div className="booking-field">
                    <span>Datum</span>
                    <DateInput
                      id="workshop-booking-start-date"
                      aria-label={selectedWorkshopIsOwn ? 'Startdatum Eigenbedarf' : 'Abholdatum'}
                      className="booking-input"
                      value={selectedWorkshopDraft?.startDate ?? ''}
                      onChange={(value) =>
                        setBookingDraft((prev) => ({ ...prev, startDate: value }))
                      }
                    />
                  </div>
                  <label>
                    <span>Uhrzeit</span>
                    <input
                      aria-label={selectedWorkshopIsOwn ? 'Startzeit Eigenbedarf' : 'Abholzeit'}
                      type="time"
                      className="booking-input"
                      value={selectedWorkshopDraft?.startTime ?? ''}
                      onChange={(event) =>
                        setBookingDraft((prev) => ({ ...prev, startTime: event.target.value }))
                      }
                    />
                  </label>
                </div>
              </div>

              <div className="booking-divider" />

              <div className="booking-section">
                <div className="booking-section-title">
                  <span />
                  <strong>{selectedWorkshopIsOwn ? 'Ende des Eigenbedarfs' : 'Abgabedaten'}</strong>
                </div>
                <div className="booking-fields-row">
                  <div className="booking-field">
                    <span>Datum</span>
                    <DateInput
                      aria-label={selectedWorkshopIsOwn ? 'Enddatum Eigenbedarf' : 'Abgabedatum'}
                      className="booking-input"
                      value={selectedWorkshopDraft?.endDate ?? ''}
                      min={selectedWorkshopDraft?.startDate}
                      onChange={(value) => setBookingDraft((prev) => ({ ...prev, endDate: value }))}
                    />
                  </div>
                  <label>
                    <span>Uhrzeit</span>
                    <input
                      aria-label={selectedWorkshopIsOwn ? 'Endzeit Eigenbedarf' : 'Abgabezeit'}
                      type="time"
                      className="booking-input"
                      value={selectedWorkshopDraft?.endTime ?? ''}
                      onChange={(event) =>
                        setBookingDraft((prev) => ({ ...prev, endTime: event.target.value }))
                      }
                    />
                  </label>
                </div>
              </div>

              {!selectedWorkshopIsOwn && <div className="booking-divider" />}

              {!selectedWorkshopIsOwn && (
                <div className="booking-section">
                  <p className="hint">
                    <strong>Werkzeuge dieser Werkstatt</strong>
                  </p>
                  {selectedWorkshop.tools.length > 0 ? (
                    <div className="workshop-booking-tools">
                      {selectedWorkshop.tools.map((tool) => (
                        <div
                          key={tool.id}
                          className={`workshop-booking-tool-option ${tool.selectable ? '' : 'is-disabled'}`.trim()}
                        >
                          <span>{tool.name}</span>
                          <small>
                            {tool.selectable
                              ? (toolCategoryByValue.get(tool.category)?.label ?? tool.category)
                              : 'Ausgeliehen'}
                          </small>
                        </div>
                      ))}
                    </div>
                  ) : (
                    <p className="hint">
                      Für diese Werkstatt wurde noch keine Ausstattung hinterlegt.
                    </p>
                  )}
                </div>
              )}

              <div className="booking-actions">
                <button
                  type="button"
                  className="booking-button"
                  onClick={() =>
                    void (selectedWorkshopIsOwn
                      ? blockWorkshopForOwnUse(selectedWorkshop.workshop.id)
                      : bookWorkshop(selectedWorkshop.workshop.id))
                  }
                  disabled={
                    !selectedWorkshopIsOwn && Boolean(token) && !selectedWorkshopDraftAvailable
                  }
                  aria-label={
                    selectedWorkshopIsOwn
                      ? `Zeitraum für ${selectedWorkshop.workshop.name} blockieren`
                      : undefined
                  }
                >
                  {selectedWorkshopIsOwn
                    ? 'Zeitraum blockieren'
                    : token
                      ? 'Anfrage senden'
                      : 'Jetzt einloggen'}
                </button>
                <p className="booking-hint">
                  {selectedWorkshopIsOwn
                    ? 'Die Blockierung gilt sofort und erzeugt keine Nachricht.'
                    : !token || selectedWorkshopDraftAvailable
                      ? 'Der Anbieter muss deine Anfrage noch bestätigen.'
                      : 'Der gewählte Zeitraum ist blockiert oder bereits gebucht.'}
                </p>
              </div>

              {token && <SystemRulesInfo token={token} />}
            </aside>
          }
        </div>

        {selectedWorkshopManageMode && (
          <div className="workshop-modal-footer owner-detail-actions">
            <Link className="btn secondary" to={`/workshops/${selectedWorkshop.workshop.id}/edit`}>
              Werkstatt bearbeiten
            </Link>
            <button type="button" className="btn danger" onClick={() => setShowDeleteDialog(true)}>
              Werkstatt löschen
            </button>
          </div>
        )}

        {showDeleteDialog && (
          <ConfirmDialog
            title="Werkstatt endgültig löschen?"
            text={`„${selectedWorkshop.workshop.name}“ und alle zugehörigen Angebotsdaten werden dauerhaft entfernt. Diese Aktion kann nicht rückgängig gemacht werden.`}
            confirmLabel="Werkstatt endgültig löschen"
            isBusy={isDeleting}
            onCancel={() => setShowDeleteDialog(false)}
            onConfirm={() => void deleteSelectedWorkshop()}
          />
        )}
      </div>

      {activeImageIndex !== null && (
        <div
          ref={imageViewerRef}
          className="workshop-image-viewer"
          role="dialog"
          aria-modal="true"
          aria-label={`Bilder von ${selectedWorkshop.workshop.name}`}
          tabIndex={-1}
        >
          <button
            ref={imageViewerCloseRef}
            type="button"
            className="workshop-image-viewer-close"
            aria-label="Bildansicht schließen"
            title="Schließen"
            onClick={closeImageViewer}
          >
            <span className="material-symbols-outlined">close</span>
          </button>
          {selectedWorkshopImages.length > 1 && (
            <button
              type="button"
              className="workshop-image-viewer-nav previous"
              aria-label="Vorheriges Bild"
              title="Vorheriges Bild"
              onClick={(event) => {
                event.stopPropagation();
                showPreviousImage();
              }}
            >
              <span className="material-symbols-outlined">chevron_left</span>
            </button>
          )}
          <div className="workshop-image-viewer-content">
            <img
              src={selectedWorkshopImages[activeImageIndex]}
              alt={`${selectedWorkshop.workshop.name}, Bild ${activeImageIndex + 1}`}
            />
            {selectedWorkshopImages.length > 1 && (
              <span className="workshop-image-viewer-counter">
                {activeImageIndex + 1} / {selectedWorkshopImages.length}
              </span>
            )}
          </div>
          {selectedWorkshopImages.length > 1 && (
            <button
              type="button"
              className="workshop-image-viewer-nav next"
              aria-label="Nächstes Bild"
              title="Nächstes Bild"
              onClick={(event) => {
                event.stopPropagation();
                showNextImage();
              }}
            >
              <span className="material-symbols-outlined">chevron_right</span>
            </button>
          )}
        </div>
      )}
    </div>
  );
}
