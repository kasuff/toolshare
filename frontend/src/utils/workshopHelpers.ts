export function getWorkshopExtras(workshop: Workshop) {
  if (workshop.extras.length > 0) {
    return workshop.extras;
  }

  const prefix = "Ausstattung:";
  if (workshop.description.startsWith(prefix)) {
    return workshop.description
      .slice(prefix.length)
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean);
  }

  return [];
}

export function isAutoGeneratedWorkshopDescription(workshop: Workshop) {
  const normalized = workshop.description.trim();
  return normalized === "Werkstatt" || normalized.startsWith("Ausstattung:");
}

export function getInitials(name: string) {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return "?";
  return parts
    .slice(0, 2)
    .map((part) => part[0])
    .join("")
    .toUpperCase();
}

export function toLocalDateKey(date: Date) {
  const year = date.getFullYear();
  const month = `${date.getMonth() + 1}`.padStart(2, "0");
  const day = `${date.getDate()}`.padStart(2, "0");
  return `${year}-${month}-${day}`;
}

export function getWorkshopCalendarDays(monthDate: Date, slots: WorkshopSlot[], bookedRanges: WorkshopBookedRange[]) {
  const year = monthDate.getFullYear();
  const month = monthDate.getMonth();
  const firstDay = new Date(year, month, 1);
  const leadingEmptyDays = (firstDay.getDay() + 6) % 7;
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  const todayKey = toLocalDateKey(new Date());
  const days: Array<{ key: string; day: number | null; dateKey?: string; available?: boolean }> = [];

  for (let index = 0; index < leadingEmptyDays; index += 1) {
    days.push({ key: `empty-${index}`, day: null });
  }

  for (let day = 1; day <= daysInMonth; day += 1) {
    const date = new Date(year, month, day);
    const dateKey = toLocalDateKey(date);
    const isPast = dateKey < todayKey;
    days.push({
      key: dateKey,
      day,
      dateKey,
      available: !isPast && !isDayUnavailable(date, slots, bookedRanges)
    });
  }

  return days;
}
