export type BookingDraft = {
  startDate: string;
  startTime: string;
  endDate: string;
  endTime: string;
};

export function getDefaultBookingDraft(): BookingDraft {
  const tomorrow = new Date();
  tomorrow.setDate(tomorrow.getDate() + 1);
  const dayAfterTomorrow = new Date(tomorrow);
  dayAfterTomorrow.setDate(dayAfterTomorrow.getDate() + 1);
  const pad = (value: number) => `${value}`.padStart(2, "0");
  const formatDate = (date: Date) => `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
  return {
    startDate: formatDate(tomorrow),
    startTime: "10:00",
    endDate: formatDate(dayAfterTomorrow),
    endTime: "10:00"
  };
}

export function combineLocalDateTimeToIso(date: string, time: string): string | null {
  const dStr = date.trim();
  const tStr = time.trim();
  if (!dStr || !tStr) return null;
  const [year, month, day] = dStr.split("-").map(Number);
  const [hour, minute] = tStr.split(":").map(Number);
  if (!year || !month || !day || Number.isNaN(hour) || Number.isNaN(minute)) return null;
  const combined = new Date(year, month - 1, day, hour, minute, 0, 0);
  if (Number.isNaN(combined.getTime())) return null;
  return combined.toISOString();
}

