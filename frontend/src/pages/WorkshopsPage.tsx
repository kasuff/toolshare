import { Link, useNavigate } from "react-router-dom";
import { useEffect, useState } from "react";
import { EmptyState, Field, SkeletonCards, Surface } from "../components/ui";
import { WORKSHOP_EQUIPMENT } from "../components/WorkshopEquipmentSelect";
import { TOOL_CATEGORIES } from "../utils/categories";
import { useToast } from "../hooks/useToast";
import { api } from "../services/api";
import type { User, Workshop, WorkshopSlot } from "../types/domain";

type Props = {
  token?: string;
  currentUser?: User;
};

type WorkshopListItem = {
  workshop: Workshop;
  slots: WorkshopSlot[];
  tools: Array<{ id: string; name: string; category: string }>;
};

type BookingDraft = {
  startDate: string;
  startTime: string;
  durationDays: number;
};

function getDefaultBookingDraft(): BookingDraft {
  const tomorrow = new Date();
  tomorrow.setDate(tomorrow.getDate() + 1);
  const pad = (value: number) => `${value}`.padStart(2, "0");
  return {
    startDate: `${tomorrow.getFullYear()}-${pad(tomorrow.getMonth() + 1)}-${pad(tomorrow.getDate())}`,
    startTime: "10:00",
    durationDays: 1
  };
}

function combineLocalDateTimeToIso(date: string, time: string): string | null {
  const dStr = date.trim();
  const tStr = time.trim();
  if (!dStr || !tStr) return null;
  const [year, month, day] = dStr.split("-").map(Number);
  const [hour, minute] = tStr.split(":").map(Number);
  if (!year || !month || !day || Number.isNaN(hour) || Number.isNaN(minute)) return null;
  const combined = new Date(year, month - 1, day, hour, minute, 0, 0);
  if (Number.isNaN(combined.getTime())) return null;
  return combined.toISOString();
}

function formatWorkshopDate(value: string) {
  return new Intl.DateTimeFormat("de-DE", {
    dateStyle: "medium",
    timeStyle: "short",
    hour12: false
  }).format(new Date(value));
}

const extrasByValue = new Map(WORKSHOP_EQUIPMENT.map((equipment) => [equipment.value, equipment] as const));
const toolCategoryByValue = new Map(TOOL_CATEGORIES.map((category) => [category.value, category] as const));
const toolCategoryIcons: Record<string, string> = {
  elektro: "bolt",
  garten: "yard",
  holz: "carpenter",
  bau: "construction",
  sanitaer: "plumbing",
  malen: "format_paint",
  kfz: "directions_car",
  sonstiges: "handyman"
};

function getWorkshopExtras(workshop: Workshop) {
  if (workshop.extras.length > 0) {
    return workshop.extras;
  }

  const prefix = "Ausstattung:";
  if (workshop.description.startsWith(prefix)) {
    return workshop.description
      .slice(prefix.length)
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean);
  }

  return [];
}

function isAutoGeneratedWorkshopDescription(workshop: Workshop) {
  const normalized = workshop.description.trim();
  return normalized === "Werkstatt" || normalized.startsWith("Ausstattung:");
}

export function WorkshopsPage({ token, currentUser }: Props) {
  const { pushToast } = useToast();
  const navigate = useNavigate();
  const [q, setQ] = useState("");
  const [toolFilter, setToolFilter] = useState("");
  const [maxCapacityFilter, setMaxCapacityFilter] = useState(10);
  const [items, setItems] = useState<WorkshopListItem[]>([]);
  const [isLoading, setIsLoading] = useState(false);
  const [hasLoaded, setHasLoaded] = useState(false);
  const [selectedWorkshop, setSelectedWorkshop] = useState<WorkshopListItem | null>(null);
  const [selectedToolIdsByWorkshop, setSelectedToolIdsByWorkshop] = useState<Record<string, string[]>>({});
  const [bookingDraftsByWorkshop, setBookingDraftsByWorkshop] = useState<Record<string, BookingDraft>>({});

  useEffect(() => {
    const run = async () => {
      setIsLoading(true);
      try {
        const workshops = await api.getWorkshops({ q }, token ?? "");
        const mapped = workshops.map(({ workshop, slots }) => {
          const tools = workshop.equipmentItems.map((tool) => ({
            id: tool.id,
            name: tool.name,
            category: tool.category
          }));
          return {
            workshop,
            slots,
            tools
          };
        });

        const filtered = toolFilter
          ? mapped.filter((item) => {
              const query = toolFilter.toLowerCase();
              return (
                item.workshop.name.toLowerCase().includes(query) ||
                item.tools.some((tool) => `${tool.name} ${tool.category}`.toLowerCase().includes(query))
              );
            })
          : mapped;
        setItems(filtered.filter((item) => item.workshop.maxCapacity <= maxCapacityFilter));
      } catch (error) {
        if (token) {
          pushToast(error instanceof Error ? error.message : "Werkstätten konnten nicht geladen werden.", "error");
        } else {
          setItems([]);
        }
      } finally {
        setIsLoading(false);
        setHasLoaded(true);
      }
    };
    void run();
  }, [q, toolFilter, token, pushToast, maxCapacityFilter]);

  const openWorkshop = (workshop: WorkshopListItem) => {
    setSelectedWorkshop(workshop);
    setBookingDraftsByWorkshop((prev) =>
      prev[workshop.workshop.id]
        ? prev
        : {
            ...prev,
            [workshop.workshop.id]: getDefaultBookingDraft()
          }
    );
  };

  const closeWorkshop = () => {
    setSelectedWorkshop(null);
  };

  const bookWorkshop = async (workshopId: string) => {
    if (!token) {
      pushToast("Zum Buchen bitte anmelden.", "info");
      navigate("/auth", { state: { redirectHint: "Bitte melde dich an, um eine Werkstatt zu buchen." } });
      return;
    }

    const selectedToolIds = selectedToolIdsByWorkshop[workshopId] ?? [];
    if (selectedToolIds.length === 0) {
      pushToast("Bitte mindestens ein Werkzeug aus der Ausstattung auswählen.", "error");
      return;
    }

    const draft = bookingDraftsByWorkshop[workshopId] ?? getDefaultBookingDraft();
    const startIso = combineLocalDateTimeToIso(draft.startDate, draft.startTime);
    if (!startIso) {
      pushToast("Bitte ein gültiges Startdatum und eine Uhrzeit angeben.", "error");
      return;
    }
    const endDate = new Date(startIso);
    endDate.setDate(endDate.getDate() + draft.durationDays);
    const endIso = endDate.toISOString();

    try {
      await api.createWorkshopBooking({ workshopId, startIso, endIso, workshopToolIds: selectedToolIds }, token);
      pushToast("Werkstattbuchung erstellt.", "success");
      setSelectedToolIdsByWorkshop((prev) => ({
        ...prev,
        [workshopId]: []
      }));
      setBookingDraftsByWorkshop((prev) => ({
        ...prev,
        [workshopId]: getDefaultBookingDraft()
      }));
      if (selectedWorkshop?.workshop.id === workshopId) {
        closeWorkshop();
      }
    } catch (error) {
      pushToast(error instanceof Error ? error.message : "Buchung fehlgeschlagen.", "error");
    }
  };

  const ownedWorkshops = currentUser ? items.filter((item) => item.workshop.ownerId === currentUser.id) : [];
  const publicWorkshops = currentUser ? items.filter((item) => item.workshop.ownerId !== currentUser.id) : items;
  const selectedWorkshopDraft = selectedWorkshop
    ? bookingDraftsByWorkshop[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()
    : null;
  const selectedWorkshopEndIso = selectedWorkshopDraft
    ? (() => {
        const startIso = combineLocalDateTimeToIso(selectedWorkshopDraft.startDate, selectedWorkshopDraft.startTime);
        if (!startIso) return null;
        const endDate = new Date(startIso);
        endDate.setDate(endDate.getDate() + selectedWorkshopDraft.durationDays);
        return endDate.toISOString();
      })()
    : null;
  const selectedWorkshopHasAvailableSlots = selectedWorkshop
    ? selectedWorkshop.slots.some((slot) => !slot.blockedByOwner)
    : false;

  const ownedStats = currentUser
    ? [
        { label: "Eigene Werkstätten", value: ownedWorkshops.length },
        { label: "Zeitfenster", value: ownedWorkshops.reduce((sum, item) => sum + item.slots.length, 0) },
        {
          label: "Durchschn. Kapazität",
          value:
            ownedWorkshops.length > 0
              ? Math.round(ownedWorkshops.reduce((sum, item) => sum + item.workshop.maxCapacity, 0) / ownedWorkshops.length)
              : 0
        }
      ]
    : [];

  return (
    <section className="stack">
      <div className="page-header">
        <div className="stack">
          <h1>Werkstätten</h1>
          <p className="subtitle">Klicke auf eine Werkstatt, um Details und Buchungsfenster in einem Fenster zu sehen.</p>
        </div>
        {token && (
          <button className="btn" onClick={() => navigate("/workshops/new")}>
            <span className="material-symbols-outlined">add</span>
            Neue Werkstatt
          </button>
        )}
      </div>

      {currentUser && (
        <Surface title="Meine Werkstätten" subtitle="Eigene Räume und Verfügbarkeiten auf einen Blick.">
          {ownedWorkshops.length > 0 ? (
            <div className="workshop-dashboard">
              <div className="workshop-dashboard-stats">
                {ownedStats.map((stat) => (
                  <div key={stat.label} className="workshop-dashboard-stat">
                    <span>{stat.label}</span>
                    <strong>{stat.value}</strong>
                  </div>
                ))}
              </div>

              <div className="workshop-dashboard-grid">
                {ownedWorkshops.map((item) => (
                  <article
                    key={item.workshop.id}
                    className={`workshop-card ${selectedWorkshop?.workshop.id === item.workshop.id ? "selected" : ""}`}
                    role="button"
                    tabIndex={0}
                    onClick={() => openWorkshop(item)}
                    onKeyDown={(event) => {
                      if (event.key === "Enter" || event.key === " ") {
                        event.preventDefault();
                        openWorkshop(item);
                      }
                    }}
                  >
                    <div className="workshop-card-media">
                      <img src={item.workshop.imageUrls[0]} alt={item.workshop.name} />
                      <span className="workshop-card-badge">Aktiv</span>
                    </div>
                    <div className="workshop-card-content">
                      <div className="workshop-card-heading">
                        <h3>{item.workshop.name}</h3>
                        <span className="workshop-card-rating">{item.slots.length} Slots</span>
                      </div>
                      <p>
                        {item.workshop.location} · {item.workshop.maxCapacity} Plätze
                      </p>
                      <div className="workshop-card-footer">
                        <button
                          type="button"
                          className="btn secondary"
                          onClick={(event) => {
                            event.stopPropagation();
                            navigate(`/workshops/${item.workshop.id}/edit`);
                          }}
                        >
                          Werkstatt bearbeiten
                        </button>
                        <button
                          type="button"
                          className="btn secondary"
                          onClick={(event) => {
                            event.stopPropagation();
                            navigate("/workshops/availability");
                          }}
                        >
                          Verfügbarkeit verwalten
                        </button>
                      </div>
                    </div>
                  </article>
                ))}
              </div>
            </div>
          ) : (
            <EmptyState title="Noch keine eigenen Werkstätten" text="Erstelle eine Werkstatt, um sie hier zu verwalten." />
          )}
        </Surface>
      )}

      <Surface title="Suche" className="interactive">
        <div className="filter-toolbar">
          <p className="result-summary">
            {isLoading ? "Suche läuft..." : `${items.length} Ergebnis${items.length === 1 ? "" : "se"}`}
          </p>
          {(q || toolFilter || maxCapacityFilter !== 10) && (
            <button
              className="btn secondary"
              onClick={() => {
                setQ("");
                setToolFilter("");
                setMaxCapacityFilter(10);
              }}
            >
              Filter zurücksetzen
            </button>
          )}
        </div>
        <div className="grid grid-2">
          <Field label="Werkstattname oder Beschreibung">
            <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Suche Werkstatt" />
          </Field>
          <Field label="Werkzeugfilter (Textmatch)">
            <input value={toolFilter} onChange={(e) => setToolFilter(e.target.value)} placeholder="Werkzeugfilter" />
          </Field>
        </div>
        <div className="slider-row">
          <label htmlFor="capacity-slider">
            Maximale Kapazität bis: <strong>{maxCapacityFilter}</strong>
          </label>
          <input
            id="capacity-slider"
            type="range"
            min={1}
            max={20}
            value={maxCapacityFilter}
            onChange={(e) => setMaxCapacityFilter(Number(e.target.value))}
          />
        </div>
        <details>
          <summary>Erweiterte Filter anzeigen</summary>
          <p className="hint">Weitere Filter (Ausstattung, Entfernung, Bewertung) können hier ergänzt werden.</p>
        </details>
      </Surface>

      <div className="cards">
        {isLoading && <SkeletonCards />}
        {!isLoading && hasLoaded && items.length === 0 && (
          <EmptyState title="Keine Werkstätten gefunden" text="Passe die Suche an oder prüfe später erneut." />
        )}
        {publicWorkshops.map((item) => (
          <article
            key={item.workshop.id}
            className={`workshop-card workshop-card-public card-enter ${selectedWorkshop?.workshop.id === item.workshop.id ? "selected" : ""}`}
            role="button"
            tabIndex={0}
            onClick={() => openWorkshop(item)}
            onKeyDown={(event) => {
              if (event.key === "Enter" || event.key === " ") {
                event.preventDefault();
                openWorkshop(item);
              }
            }}
          >
            <div className="workshop-card-media">
              <img src={item.workshop.imageUrls[0]} alt={item.workshop.name} />
              <span className="workshop-card-badge">{item.slots.length} Zeitfenster</span>
            </div>
            <div className="workshop-card-content">
              <div className="workshop-card-heading">
                <h3>{item.workshop.name}</h3>
                <span className="workshop-card-rating">{item.workshop.maxCapacity} Plätze</span>
              </div>
              <p>{item.workshop.location}</p>
              <p>{item.workshop.description}</p>
            </div>
          </article>
        ))}
      </div>

      {selectedWorkshop && (
        <div className="workshop-modal-backdrop" role="presentation" onClick={closeWorkshop}>
          <div
            className="workshop-modal"
            role="dialog"
            aria-modal="true"
            aria-label={selectedWorkshop.workshop.name}
            onClick={(event) => event.stopPropagation()}
          >
            <div className="workshop-modal-header">
              <div>
                <p className="eyebrow">Werkstattdetails</p>
                <h2>{selectedWorkshop.workshop.name}</h2>
                <p className="subtitle">{selectedWorkshop.workshop.location}</p>
              </div>
              <button type="button" className="icon-button workshop-modal-close" onClick={closeWorkshop} aria-label="Fenster schließen">
                <span className="material-symbols-outlined">close</span>
              </button>
            </div>

            <div className="workshop-modal-body">
              {!isAutoGeneratedWorkshopDescription(selectedWorkshop.workshop) && <p>{selectedWorkshop.workshop.description}</p>}
              <div className="workshop-modal-meta">
                <span className="status-pill neutral">{selectedWorkshop.workshop.maxCapacity} Plätze</span>
                <span className="status-pill neutral">{selectedWorkshop.slots.length} Zeitfenster</span>
                {currentUser && selectedWorkshop.workshop.ownerId === currentUser.id && (
                  <span className="status-pill success">Eigene Werkstatt</span>
                )}
              </div>

              {selectedWorkshop.workshop.equipmentItems.length > 0 && (
                <>
                  <p className="hint"><strong>Ausstattung</strong></p>
                  <div className="workshop-equipment-list">
                    {selectedWorkshop.workshop.equipmentItems.map((item) => {
                      const category = toolCategoryByValue.get(item.category);
                      return (
                        <span key={item.id} className="workshop-equipment-chip">
                          <span className="material-symbols-outlined">{toolCategoryIcons[item.category] ?? "construction"}</span>
                          <span>{item.name}</span>
                          <small>{category?.label ?? item.category}</small>
                        </span>
                      );
                    })}
                  </div>
                </>
              )}

              {getWorkshopExtras(selectedWorkshop.workshop).length > 0 && (
                <>
                  <p className="hint"><strong>Extras</strong></p>
                  <div className="workshop-equipment-list">
                    {getWorkshopExtras(selectedWorkshop.workshop).map((extraValue) => {
                      const extra = extrasByValue.get(extraValue);
                      return (
                        <span key={extraValue} className="workshop-equipment-chip">
                          <span className="material-symbols-outlined">{extra?.icon ?? "construction"}</span>
                          <span>{extra?.label ?? extraValue}</span>
                        </span>
                      );
                    })}
                  </div>
                </>
              )}

              <div className="time-slots-display">
                {currentUser?.id !== selectedWorkshop.workshop.ownerId && (
                  <div className="playtomic-booking-panel">
                    <h3>Werkstatt buchen</h3>

                    <div className="booking-section">
                      <label className="booking-label" htmlFor="workshop-booking-start-date">
                        Von wann?
                      </label>
                      <input
                        id="workshop-booking-start-date"
                        type="date"
                        className="booking-input"
                        value={selectedWorkshopDraft?.startDate ?? ""}
                        onChange={(event) =>
                          setBookingDraftsByWorkshop((prev) => ({
                            ...prev,
                            [selectedWorkshop.workshop.id]: {
                              ...(prev[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()),
                              startDate: event.target.value
                            }
                          }))
                        }
                      />
                      <input
                        type="time"
                        className="booking-input"
                        style={{ marginTop: "8px" }}
                        value={selectedWorkshopDraft?.startTime ?? ""}
                        onChange={(event) =>
                          setBookingDraftsByWorkshop((prev) => ({
                            ...prev,
                            [selectedWorkshop.workshop.id]: {
                              ...(prev[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()),
                              startTime: event.target.value
                            }
                          }))
                        }
                      />
                    </div>

                    <div className="booking-section">
                      <label className="booking-label">Wie lange?</label>
                      <div className="duration-picker">
                        <button
                          type="button"
                          className="duration-btn"
                          onClick={() =>
                            setBookingDraftsByWorkshop((prev) => ({
                              ...prev,
                              [selectedWorkshop.workshop.id]: {
                                ...(prev[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()),
                                durationDays: Math.max(
                                  1,
                                  (prev[selectedWorkshop.workshop.id]?.durationDays ?? getDefaultBookingDraft().durationDays) - 1
                                )
                              }
                            }))
                          }
                        >
                          −
                        </button>
                        <div className="duration-display">
                          <strong>{selectedWorkshopDraft?.durationDays ?? 1}</strong>
                          <span className="duration-label">
                            {(selectedWorkshopDraft?.durationDays ?? 1) === 1 ? "Tag" : "Tage"}
                          </span>
                        </div>
                        <button
                          type="button"
                          className="duration-btn"
                          onClick={() =>
                            setBookingDraftsByWorkshop((prev) => ({
                              ...prev,
                              [selectedWorkshop.workshop.id]: {
                                ...(prev[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()),
                                durationDays: Math.min(
                                  30,
                                  (prev[selectedWorkshop.workshop.id]?.durationDays ?? getDefaultBookingDraft().durationDays) + 1
                                )
                              }
                            }))
                          }
                        >
                          +
                        </button>
                      </div>
                      {selectedWorkshopEndIso && (
                        <p className="booking-end-date">
                          Ende: <strong>{formatWorkshopDate(selectedWorkshopEndIso)}</strong>
                        </p>
                      )}
                    </div>

                    <div className="booking-section">
                      <p className="hint">
                        <strong>Benötigte Werkzeuge (mindestens eins)</strong>
                      </p>
                      {selectedWorkshop.tools.length > 0 ? (
                        <>
                          <div className="row" style={{ marginBottom: "0.5rem" }}>
                            <button
                              type="button"
                              className="btn secondary"
                              onClick={() =>
                                setSelectedToolIdsByWorkshop((prev) => ({
                                  ...prev,
                                  [selectedWorkshop.workshop.id]: selectedWorkshop.tools.map((tool) => tool.id)
                                }))
                              }
                            >
                              Alle auswählen
                            </button>
                            <button
                              type="button"
                              className="btn ghost"
                              onClick={() =>
                                setSelectedToolIdsByWorkshop((prev) => ({
                                  ...prev,
                                  [selectedWorkshop.workshop.id]: []
                                }))
                              }
                            >
                              Auswahl löschen
                            </button>
                          </div>
                          <div className="workshop-booking-tools">
                            {selectedWorkshop.tools.map((tool) => {
                              const selectedToolIds = selectedToolIdsByWorkshop[selectedWorkshop.workshop.id] ?? [];
                              const checked = selectedToolIds.includes(tool.id);
                              return (
                                <label key={tool.id} className="workshop-booking-tool-option">
                                  <input
                                    type="checkbox"
                                    checked={checked}
                                    disabled={!token}
                                    onChange={(event) =>
                                      setSelectedToolIdsByWorkshop((prev) => {
                                        const current = prev[selectedWorkshop.workshop.id] ?? [];
                                        const next = event.target.checked
                                          ? Array.from(new Set([...current, tool.id]))
                                          : current.filter((id) => id !== tool.id);
                                        return {
                                          ...prev,
                                          [selectedWorkshop.workshop.id]: next
                                        };
                                      })
                                    }
                                  />
                                  <span>{tool.name}</span>
                                  <small>{toolCategoryByValue.get(tool.category)?.label ?? tool.category}</small>
                                </label>
                              );
                            })}
                          </div>
                        </>
                      ) : (
                        <p className="hint">Für diese Werkstatt wurde noch keine Ausstattung hinterlegt.</p>
                      )}
                    </div>

                    <button
                      type="button"
                      className="booking-button"
                      onClick={() => void bookWorkshop(selectedWorkshop.workshop.id)}
                      disabled={!selectedWorkshopHasAvailableSlots}
                    >
                      {token ? "Anfrage senden" : "Login"}
                    </button>
                    <p className="booking-hint">
                      {selectedWorkshopHasAvailableSlots
                        ? "Der Anbieter muss deine Anfrage noch bestätigen."
                        : "Aktuell ist kein verfügbares Zeitfenster hinterlegt."}
                    </p>
                  </div>
                )}

                {selectedWorkshop.slots.length > 0 ? (
                  <ul className="meta-list">
                    {selectedWorkshop.slots.map((slot) => (
                      <li key={slot.id} className="slot-item">
                        <div>
                          <strong>{formatWorkshopDate(slot.startIso)}</strong>
                          <span> bis </span>
                          <strong>{formatWorkshopDate(slot.endIso)}</strong>
                          {slot.blockedByOwner && <span className="slot-badge">blockiert</span>}
                        </div>
                      </li>
                    ))}
                  </ul>
                ) : (
                  <p className="hint">Keine Zeitfenster hinterlegt.</p>
                )}
              </div>
            </div>

            {currentUser && selectedWorkshop.workshop.ownerId === currentUser.id && (
              <div className="workshop-modal-footer">
                <Link className="btn secondary" to={`/workshops/${selectedWorkshop.workshop.id}/edit`} onClick={closeWorkshop}>
                  Werkstatt bearbeiten
                </Link>
                <Link className="btn" to="/workshops/availability" onClick={closeWorkshop}>
                  Verfügbarkeit verwalten
                </Link>
              </div>
            )}
          </div>
        </div>
      )}
    </section>
  );
}
