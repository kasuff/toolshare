import { Link, useNavigate, useParams, useSearchParams } from "react-router-dom";
import { useEffect, useMemo, useState } from "react";
import { DetailTopBar } from "../components/DetailTopBar";
import { ReportFormPanel } from "../components/ReportFormPanel";
import { SearchRadiusMap } from "../components/SearchRadiusMap";
import { EmptyState, Field, SkeletonCards, Surface } from "../components/ui";
import { WORKSHOP_EQUIPMENT } from "../components/workshop-equipment";
import { DEFAULT_PLACEHOLDER_IMAGE, TOOL_CATEGORIES } from "../utils/categories";
import { useToast } from "../hooks/useToast";
import { api } from "../services/api";
import { distanceBetweenLocations, hasMatchingSlot, isWithinRadius } from "../utils/searchFilters";
import type { Tool, User, Workshop, WorkshopSlot } from "../types/domain";

type Props = {
  token?: string;
  currentUser?: User;
};

type WorkshopListItem = {
  workshop: Workshop;
  slots: WorkshopSlot[];
  tools: Array<Tool & { selectable: boolean }>;
};

type BookingDraft = {
  startDate: string;
  startTime: string;
  durationDays: number;
};

function getDefaultBookingDraft(): BookingDraft {
  const tomorrow = new Date();
  tomorrow.setDate(tomorrow.getDate() + 1);
  const pad = (value: number) => `${value}`.padStart(2, "0");
  return {
    startDate: `${tomorrow.getFullYear()}-${pad(tomorrow.getMonth() + 1)}-${pad(tomorrow.getDate())}`,
    startTime: "10:00",
    durationDays: 1
  };
}

function combineLocalDateTimeToIso(date: string, time: string): string | null {
  const dStr = date.trim();
  const tStr = time.trim();
  if (!dStr || !tStr) return null;
  const [year, month, day] = dStr.split("-").map(Number);
  const [hour, minute] = tStr.split(":").map(Number);
  if (!year || !month || !day || Number.isNaN(hour) || Number.isNaN(minute)) return null;
  const combined = new Date(year, month - 1, day, hour, minute, 0, 0);
  if (Number.isNaN(combined.getTime())) return null;
  return combined.toISOString();
}

function formatWorkshopDate(value: string) {
  return new Intl.DateTimeFormat("de-DE", {
    dateStyle: "medium",
    timeStyle: "short",
    hour12: false
  }).format(new Date(value));
}

const extrasByValue = new Map(WORKSHOP_EQUIPMENT.map((equipment) => [equipment.value, equipment] as const));
const toolCategoryByValue = new Map(TOOL_CATEGORIES.map((category) => [category.value, category] as const));
const toolCategoryIcons: Record<string, string> = {
  elektro: "bolt",
  garten: "yard",
  holz: "carpenter",
  bau: "construction",
  sanitaer: "plumbing",
  malen: "format_paint",
  kfz: "directions_car",
  sonstiges: "handyman"
};

function getWorkshopExtras(workshop: Workshop) {
  if (workshop.extras.length > 0) {
    return workshop.extras;
  }

  const prefix = "Ausstattung:";
  if (workshop.description.startsWith(prefix)) {
    return workshop.description
      .slice(prefix.length)
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean);
  }

  return [];
}

function isAutoGeneratedWorkshopDescription(workshop: Workshop) {
  const normalized = workshop.description.trim();
  return normalized === "Werkstatt" || normalized.startsWith("Ausstattung:");
}

function formatCardDistance(distance: number | null) {
  return distance === null ? "Distanz offen" : `${distance.toFixed(1)} km`;
}

function getInitials(name: string) {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return "?";
  return parts
    .slice(0, 2)
    .map((part) => part[0])
    .join("")
    .toUpperCase();
}

export function WorkshopsPage({ token, currentUser }: Props) {
  const { pushToast } = useToast();
  const navigate = useNavigate();
  const { id: selectedWorkshopId } = useParams<{ id?: string }>();
  const [searchParams] = useSearchParams();
  const openWorkshopId = searchParams.get("open");
  const [q, setQ] = useState("");
  const [toolFilter, setToolFilter] = useState("");
  const [maxCapacityFilter, setMaxCapacityFilter] = useState(10);
  const [borrowFrom, setBorrowFrom] = useState("");
  const [borrowUntil, setBorrowUntil] = useState("");
  const [radiusKm, setRadiusKm] = useState(5);
  const defaultLocation = currentUser?.address ?? "München Zentrum";
  const [items, setItems] = useState<WorkshopListItem[]>([]);
  const [isLoading, setIsLoading] = useState(false);
  const [hasLoaded, setHasLoaded] = useState(false);
  const [showReportForm, setShowReportForm] = useState(false);
  const [reportReason, setReportReason] = useState("");
  const [reportDetails, setReportDetails] = useState("");
  const [isReporting, setIsReporting] = useState(false);
  const [selectedToolIdsByWorkshop, setSelectedToolIdsByWorkshop] = useState<Record<string, string[]>>({});
  const [bookingDraftsByWorkshop, setBookingDraftsByWorkshop] = useState<Record<string, BookingDraft>>({});

  useEffect(() => {
    const run = async () => {
      setIsLoading(true);
      try {
        const workshops = await api.getWorkshops({ q }, token ?? "");
        const mapped = workshops.map(({ workshop, slots, tools }) => ({
          workshop,
          slots,
          tools:
            tools ??
            workshop.equipmentItems.map((item) => ({
              id: item.id,
              ownerId: workshop.ownerId,
              ownerName: workshop.ownerName,
              name: item.name,
              description: "Werkstatt-Werkzeug",
              category: item.category,
              imageUrl: DEFAULT_PLACEHOLDER_IMAGE,
              status: "VERFUEGBAR" as const,
              selectable: true
            }))
        }));
        setItems(mapped);
      } catch (error) {
        if (token) {
          pushToast(error instanceof Error ? error.message : "Werkstätten konnten nicht geladen werden.", "error");
        } else {
          setItems([]);
        }
      } finally {
        setIsLoading(false);
        setHasLoaded(true);
      }
    };
    void run();
  }, [q, token, pushToast]);

  const toolFilterOptions = useMemo(() => {
    const options = new Map<string, string>();
    items.forEach((item) => {
      item.tools
        .filter((tool) => tool.selectable)
        .forEach((tool) => {
          options.set(tool.id, tool.name);
        });
    });
    return Array.from(options, ([value, label]) => ({ value, label })).sort((a, b) => a.label.localeCompare(b.label));
  }, [items]);

  const candidateItems = useMemo(() => {
    return items
      .filter((item) => {
        if (!toolFilter) return true;
        return item.tools.some(
          (tool) =>
            tool.selectable &&
            (tool.id === toolFilter || tool.name.toLowerCase().includes(toolFilter.toLowerCase()) || tool.category === toolFilter)
        );
      })
      .filter((item) => item.workshop.maxCapacity <= maxCapacityFilter)
      .filter((item) => hasMatchingSlot(item.slots, borrowFrom, borrowUntil));
  }, [borrowFrom, borrowUntil, items, maxCapacityFilter, toolFilter]);

  const filteredItems = useMemo(() => {
    return candidateItems.filter((item) => isWithinRadius(defaultLocation, item.workshop.location, radiusKm));
  }, [candidateItems, defaultLocation, radiusKm]);

  const selectedWorkshop = useMemo(() => {
    const workshopId = selectedWorkshopId ?? openWorkshopId;
    if (!workshopId) return null;
    return items.find((item) => item.workshop.id === workshopId) ?? null;
  }, [items, openWorkshopId, selectedWorkshopId]);

  useEffect(() => {
    if (!openWorkshopId || selectedWorkshopId === openWorkshopId || items.length === 0) return;
    const match = items.find((item) => item.workshop.id === openWorkshopId);
    if (match) {
      navigate(`/workshops/${openWorkshopId}`, { replace: true });
    }
  }, [items, navigate, openWorkshopId, selectedWorkshopId]);

  const hasActiveFilters = Boolean(
    q || toolFilter || borrowFrom || borrowUntil || maxCapacityFilter !== 10 || radiusKm !== 5
  );

  const resetFilters = () => {
    setQ("");
    setToolFilter("");
    setBorrowFrom("");
    setBorrowUntil("");
    setMaxCapacityFilter(10);
    setRadiusKm(5);
  };

  const openWorkshop = (workshop: WorkshopListItem) => {
    setBookingDraftsByWorkshop((prev) =>
      prev[workshop.workshop.id]
        ? prev
        : {
            ...prev,
            [workshop.workshop.id]: getDefaultBookingDraft()
          }
    );
    setSelectedToolIdsByWorkshop((prev) =>
      prev[workshop.workshop.id]
        ? prev
        : {
            ...prev,
            [workshop.workshop.id]: workshop.tools.filter((tool) => tool.selectable).map((tool) => tool.id)
          }
    );
    navigate(`/workshops/${workshop.workshop.id}`);
  };

  const closeReportForm = () => {
    setShowReportForm(false);
    setReportReason("");
    setReportDetails("");
  };

  const closeWorkshop = () => {
    closeReportForm();
    navigate("/workshops");
  };

  const bookWorkshop = async (workshopId: string) => {
    if (!token) {
      pushToast("Zum Buchen bitte anmelden.", "info");
      navigate("/auth", { state: { redirectHint: "Bitte melde dich an, um eine Werkstatt zu buchen." } });
      return;
    }

    const selectedToolIds = selectedToolIdsByWorkshop[workshopId] ?? [];
    if (selectedToolIds.length === 0) {
      pushToast("Bitte mindestens ein Werkzeug aus der Ausstattung auswählen.", "error");
      return;
    }

    const draft = bookingDraftsByWorkshop[workshopId] ?? getDefaultBookingDraft();
    const startIso = combineLocalDateTimeToIso(draft.startDate, draft.startTime);
    if (!startIso) {
      pushToast("Bitte ein gültiges Startdatum und eine Uhrzeit angeben.", "error");
      return;
    }
    const endDate = new Date(startIso);
    endDate.setDate(endDate.getDate() + draft.durationDays);
    const endIso = endDate.toISOString();

    try {
      await api.createWorkshopBooking({ workshopId, startIso, endIso, workshopToolIds: selectedToolIds }, token);
      pushToast("Werkstattbuchung erstellt.", "success");
      setSelectedToolIdsByWorkshop((prev) => ({
        ...prev,
        [workshopId]: []
      }));
      setBookingDraftsByWorkshop((prev) => ({
        ...prev,
        [workshopId]: getDefaultBookingDraft()
      }));
      if (selectedWorkshop?.workshop.id === workshopId) {
        closeWorkshop();
      }
    } catch (error) {
      pushToast(error instanceof Error ? error.message : "Buchung fehlgeschlagen.", "error");
    }
  };

  const openReportForm = () => {
    if (!token) {
      navigate("/auth", { state: { redirectHint: "Bitte melde dich an, um ein Angebot zu melden." } });
      return;
    }
    setShowReportForm(true);
  };

  const reportWorkshop = async (workshopId: string) => {
    if (reportReason.trim().length < 5) {
      pushToast("Bitte gib einen Grund mit mindestens 5 Zeichen an.", "error");
      return;
    }
    setIsReporting(true);
    try {
      await api.createReport(
        {
          targetType: "WORKSHOP",
          targetId: workshopId,
          reason: reportReason.trim(),
          details: reportDetails.trim() || undefined
        },
        token!
      );
      closeReportForm();
      pushToast("Werkstatt wurde gemeldet.", "success");
    } catch (error) {
      pushToast(error instanceof Error ? error.message : "Meldung konnte nicht gesendet werden.", "error");
    } finally {
      setIsReporting(false);
    }
  };

  const ownedWorkshops = currentUser ? items.filter((item) => item.workshop.ownerId === currentUser.id) : [];
  const publicWorkshops = currentUser
    ? filteredItems.filter((item) => item.workshop.ownerId !== currentUser.id)
    : filteredItems;
  const selectedWorkshopDraft = selectedWorkshop
    ? bookingDraftsByWorkshop[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()
    : null;
  const selectedWorkshopEndIso = selectedWorkshopDraft
    ? (() => {
        const startIso = combineLocalDateTimeToIso(selectedWorkshopDraft.startDate, selectedWorkshopDraft.startTime);
        if (!startIso) return null;
        const endDate = new Date(startIso);
        endDate.setDate(endDate.getDate() + selectedWorkshopDraft.durationDays);
        return endDate.toISOString();
      })()
    : null;
  const selectedWorkshopHasAvailableSlots = selectedWorkshop
    ? selectedWorkshop.slots.some((slot) => !slot.blockedByOwner)
    : false;

  const ownedStats = currentUser
    ? [
        { label: "Eigene Werkstätten", value: ownedWorkshops.length },
        { label: "Zeitfenster", value: ownedWorkshops.reduce((sum, item) => sum + item.slots.length, 0) },
        {
          label: "Durchschn. Kapazität",
          value:
            ownedWorkshops.length > 0
              ? Math.round(ownedWorkshops.reduce((sum, item) => sum + item.workshop.maxCapacity, 0) / ownedWorkshops.length)
              : 0
        }
      ]
    : [];

  return (
    <section className="stack search-page">
      <div className="offer-strip">
        <div>
          <h2>Easy verleihen. Schnell Nachbarn helfen.</h2>
          <p>Jetzt ganz einfach private Werkstätten einstellen.</p>
        </div>
        {token && (
          <button className="btn offer-tool" onClick={() => navigate("/workshops/new")}>
            Werkstatt anbieten
          </button>
        )}
      </div>

      <div className="page-header">
        <div className="stack">
          <h1>Werkstätten</h1>
          <p className="subtitle">Klicke auf eine Werkstatt, um Details und Buchungsfenster in einem Fenster zu sehen.</p>
        </div>
      </div>

      {currentUser && (
        <Surface title="Meine Werkstätten" subtitle="Eigene Räume und Verfügbarkeiten auf einen Blick.">
          {ownedWorkshops.length > 0 ? (
            <div className="workshop-dashboard">
              <div className="workshop-dashboard-stats">
                {ownedStats.map((stat) => (
                  <div key={stat.label} className="workshop-dashboard-stat">
                    <span>{stat.label}</span>
                    <strong>{stat.value}</strong>
                  </div>
                ))}
              </div>

              <div className="workshop-dashboard-grid">
                {ownedWorkshops.map((item) => (
                  <article
                    key={item.workshop.id}
                    className={`workshop-card ${selectedWorkshop?.workshop.id === item.workshop.id ? "selected" : ""}`}
                    role="button"
                    tabIndex={0}
                    onClick={() => openWorkshop(item)}
                    onKeyDown={(event) => {
                      if (event.key === "Enter" || event.key === " ") {
                        event.preventDefault();
                        openWorkshop(item);
                      }
                    }}
                  >
                    <div className="workshop-card-media">
                      <img src={item.workshop.imageUrls[0] ?? DEFAULT_PLACEHOLDER_IMAGE} alt={item.workshop.name} />
                      <span className="workshop-card-badge">Aktiv</span>
                    </div>
                    <div className="workshop-card-content">
                      <div className="workshop-card-heading">
                        <h3>{item.workshop.name}</h3>
                        <span className="workshop-card-rating">{item.slots.length} Slots</span>
                      </div>
                      <p>
                        {item.workshop.location} · {item.workshop.maxCapacity} Plätze
                      </p>
                      <div className="workshop-card-footer">
                        <button
                          type="button"
                          className="btn secondary"
                          onClick={(event) => {
                            event.stopPropagation();
                            navigate(`/workshops/${item.workshop.id}/edit`);
                          }}
                        >
                          Werkstatt bearbeiten
                        </button>
                        <button
                          type="button"
                          className="btn secondary"
                          onClick={(event) => {
                            event.stopPropagation();
                            navigate("/workshops/availability");
                          }}
                        >
                          Verfügbarkeit verwalten
                        </button>
                      </div>
                    </div>
                  </article>
                ))}
              </div>
            </div>
          ) : (
            <EmptyState title="Noch keine eigenen Werkstätten" text="Erstelle eine Werkstatt, um sie hier zu verwalten." />
          )}
        </Surface>
      )}

      <Surface title="Suche und Filter" className="interactive">
        <div className="filter-toolbar">
          <p className="result-summary">
            {isLoading ? "Suche läuft..." : `${publicWorkshops.length} Ergebnis${publicWorkshops.length === 1 ? "" : "se"}`}
          </p>
          {hasActiveFilters && (
            <button type="button" className="btn secondary" onClick={resetFilters}>
              Filter zurücksetzen
            </button>
          )}
        </div>
        <div className="grid grid-2">
          <Field label="Suche">
            <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Werkstattname oder Beschreibung" />
          </Field>
          <Field label="Werkzeugfilter">
            <select value={toolFilter} onChange={(e) => setToolFilter(e.target.value)}>
              <option value="">Alle verfügbaren Werkzeuge</option>
              {toolFilterOptions.map((item) => (
                <option key={item.value} value={item.value}>
                  {item.label}
                </option>
              ))}
            </select>
          </Field>
        </div>
        <details className="advanced-filter-panel">
          <summary>Erweiterte Filter anzeigen</summary>
          <div className="advanced-filter-grid">
            <div className="advanced-filter-fields">
              <div className="grid grid-2">
                <Field label="Ausleihe von">
                  <input type="date" value={borrowFrom} onChange={(e) => setBorrowFrom(e.target.value)} />
                </Field>
                <Field label="Ausleihe bis">
                  <input type="date" value={borrowUntil} onChange={(e) => setBorrowUntil(e.target.value)} />
                </Field>
              </div>
              <div className="slider-row">
                <label htmlFor="capacity-slider">
                  Maximale Kapazität bis: <strong>{maxCapacityFilter}</strong>
                </label>
                <input
                  id="capacity-slider"
                  type="range"
                  min={1}
                  max={20}
                  value={maxCapacityFilter}
                  onChange={(e) => setMaxCapacityFilter(Number(e.target.value))}
                />
              </div>
            </div>
            <SearchRadiusMap
              centerAddress={defaultLocation}
              points={candidateItems.map((item) => ({
                id: item.workshop.id,
                label: item.workshop.name,
                location: item.workshop.location
              }))}
              radiusKm={radiusKm}
              onRadiusChange={setRadiusKm}
              sliderId="workshop-radius-slider"
            />
          </div>
        </details>
      </Surface>

      <div className={`cards ${!isLoading && hasLoaded && publicWorkshops.length === 0 ? "cards-empty" : ""}`}>
        {isLoading && <SkeletonCards />}
        {!isLoading && hasLoaded && publicWorkshops.length === 0 && (
          <EmptyState title="Keine Werkstatt gefunden" text="Passe die Suche an oder prüfe später erneut." />
        )}
        {publicWorkshops.map((item) => {
          const distance = distanceBetweenLocations(defaultLocation, item.workshop.location);
          const ownerName = item.workshop.ownerName ?? "Unbekannt";
          const primaryImage = item.workshop.imageUrls[0];
          const cardImage = primaryImage || DEFAULT_PLACEHOLDER_IMAGE;
          const isWorkshopAvailable = item.slots.some((slot) => !slot.blockedByOwner);
          return (
            <article
              key={item.workshop.id}
              className={`ds-workshop-card card-enter ${selectedWorkshop?.workshop.id === item.workshop.id ? "selected" : ""}`}
              role="button"
              tabIndex={0}
              onClick={() => openWorkshop(item)}
              onKeyDown={(event) => {
                if (event.key === "Enter" || event.key === " ") {
                  event.preventDefault();
                  openWorkshop(item);
                }
              }}
            >
              <div className="ds-workshop-card-media">
                <span className={`ds-workshop-card-badge ${isWorkshopAvailable ? "" : "unavailable"}`.trim()}>
                  {isWorkshopAvailable ? "✓ Verfügbar" : "✕ Nicht verfügbar"}
                </span>
                {cardImage ? (
                  <img className="ds-workshop-card-image" src={cardImage} alt={item.workshop.name} />
                ) : (
                  <div className="ds-workshop-card-icon" aria-label={item.workshop.name} title={item.workshop.name}>
                    🪛
                  </div>
                )}
              </div>
              <div className="ds-workshop-card-body">
                <div className="ds-workshop-card-distance">{formatCardDistance(distance)}</div>
                <h3>{item.workshop.name}</h3>
                <p className="ds-workshop-card-description">{item.workshop.description}</p>
                <div className="ds-workshop-card-divider" />
                <div className="ds-workshop-card-footer">
                  <div className="ds-workshop-card-owner">
                    <span className="ds-workshop-card-avatar">{getInitials(ownerName)}</span>
                    <span>{ownerName}</span>
                  </div>
                  <span className="ds-workshop-card-details">Details</span>
                </div>
              </div>
            </article>
          );
        })}
      </div>

      {selectedWorkshop && (
        <div className="workshop-modal-backdrop" role="presentation" onClick={closeWorkshop}>
          <div
            className="workshop-modal"
            role="dialog"
            aria-modal="true"
            aria-label={selectedWorkshop.workshop.name}
            onClick={(event) => event.stopPropagation()}
          >
            <div className="workshop-modal-toolbar">
              <DetailTopBar onBack={closeWorkshop}>
                {currentUser?.id !== selectedWorkshop.workshop.ownerId && (
                  <button type="button" className="detail-report-trigger" onClick={openReportForm}>
                    Werkstatt melden
                  </button>
                )}
              </DetailTopBar>
            </div>

            {showReportForm && currentUser?.id !== selectedWorkshop.workshop.ownerId && (
              <ReportFormPanel
                title="Werkstatt melden"
                hint="Wenn Regeln verletzt werden, melde diese Werkstatt der Moderation."
                reason={reportReason}
                details={reportDetails}
                isSubmitting={isReporting}
                submitLabel="Werkstatt melden"
                onReasonChange={setReportReason}
                onDetailsChange={setReportDetails}
                onSubmit={() => void reportWorkshop(selectedWorkshop.workshop.id)}
                onCancel={closeReportForm}
              />
            )}

            <div className="workshop-modal-header">
              <div>
                <p className="eyebrow">Werkstattdetails</p>
                <h2>{selectedWorkshop.workshop.name}</h2>
                <p className="subtitle">{selectedWorkshop.workshop.location}</p>
              </div>
            </div>

            <div className="workshop-modal-body">
              {!isAutoGeneratedWorkshopDescription(selectedWorkshop.workshop) && <p>{selectedWorkshop.workshop.description}</p>}
              <div className="workshop-modal-meta">
                <span className="status-pill neutral">{selectedWorkshop.workshop.maxCapacity} Plätze</span>
                <span className="status-pill neutral">{selectedWorkshop.slots.length} Zeitfenster</span>
                {currentUser && selectedWorkshop.workshop.ownerId === currentUser.id && (
                  <span className="status-pill success">Eigene Werkstatt</span>
                )}
              </div>

              {selectedWorkshop.tools.length > 0 && (
                <>
                  <p className="hint">
                    <strong>Werkzeuge in dieser Werkstatt</strong>
                  </p>
                  <div className="workshop-equipment-list">
                    {selectedWorkshop.tools.map((tool) => {
                      const category = toolCategoryByValue.get(tool.category);
                      return (
                        <span
                          key={tool.id}
                          className={`workshop-equipment-chip ${tool.selectable ? "" : "disabled"}`.trim()}
                          aria-disabled={!tool.selectable}
                        >
                          <span className="material-symbols-outlined">{toolCategoryIcons[tool.category] ?? "construction"}</span>
                          <span>{tool.name}</span>
                          <small>{tool.selectable ? (category?.label ?? tool.category) : "Ausgeliehen"}</small>
                        </span>
                      );
                    })}
                  </div>
                </>
              )}

              {getWorkshopExtras(selectedWorkshop.workshop).length > 0 && (
                <>
                  <p className="hint">
                    <strong>Extras</strong>
                  </p>
                  <div className="workshop-equipment-list">
                    {getWorkshopExtras(selectedWorkshop.workshop).map((extraValue) => {
                      const extra = extrasByValue.get(extraValue);
                      return (
                        <span key={extraValue} className="workshop-equipment-chip">
                          <span className="material-symbols-outlined">{extra?.icon ?? "construction"}</span>
                          <span>{extra?.label ?? extraValue}</span>
                        </span>
                      );
                    })}
                  </div>
                </>
              )}

              <div className="time-slots-display">
                {currentUser?.id !== selectedWorkshop.workshop.ownerId && (
                  <div className="playtomic-booking-panel">
                    <h3>Werkstatt buchen</h3>

                    <div className="booking-section">
                      <label className="booking-label" htmlFor="workshop-booking-start-date">
                        Von wann?
                      </label>
                      <input
                        id="workshop-booking-start-date"
                        type="date"
                        className="booking-input"
                        value={selectedWorkshopDraft?.startDate ?? ""}
                        onChange={(event) =>
                          setBookingDraftsByWorkshop((prev) => ({
                            ...prev,
                            [selectedWorkshop.workshop.id]: {
                              ...(prev[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()),
                              startDate: event.target.value
                            }
                          }))
                        }
                      />
                      <input
                        type="time"
                        className="booking-input"
                        style={{ marginTop: "8px" }}
                        value={selectedWorkshopDraft?.startTime ?? ""}
                        onChange={(event) =>
                          setBookingDraftsByWorkshop((prev) => ({
                            ...prev,
                            [selectedWorkshop.workshop.id]: {
                              ...(prev[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()),
                              startTime: event.target.value
                            }
                          }))
                        }
                      />
                    </div>

                    <div className="booking-section">
                      <label className="booking-label">Wie lange?</label>
                      <div className="duration-picker">
                        <button
                          type="button"
                          className="duration-btn"
                          onClick={() =>
                            setBookingDraftsByWorkshop((prev) => ({
                              ...prev,
                              [selectedWorkshop.workshop.id]: {
                                ...(prev[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()),
                                durationDays: Math.max(
                                  1,
                                  (prev[selectedWorkshop.workshop.id]?.durationDays ?? getDefaultBookingDraft().durationDays) - 1
                                )
                              }
                            }))
                          }
                        >
                          −
                        </button>
                        <div className="duration-display">
                          <strong>{selectedWorkshopDraft?.durationDays ?? 1}</strong>
                          <span className="duration-label">
                            {(selectedWorkshopDraft?.durationDays ?? 1) === 1 ? "Tag" : "Tage"}
                          </span>
                        </div>
                        <button
                          type="button"
                          className="duration-btn"
                          onClick={() =>
                            setBookingDraftsByWorkshop((prev) => ({
                              ...prev,
                              [selectedWorkshop.workshop.id]: {
                                ...(prev[selectedWorkshop.workshop.id] ?? getDefaultBookingDraft()),
                                durationDays: Math.min(
                                  30,
                                  (prev[selectedWorkshop.workshop.id]?.durationDays ?? getDefaultBookingDraft().durationDays) + 1
                                )
                              }
                            }))
                          }
                        >
                          +
                        </button>
                      </div>
                      {selectedWorkshopEndIso && (
                        <p className="booking-end-date">
                          Ende: <strong>{formatWorkshopDate(selectedWorkshopEndIso)}</strong>
                        </p>
                      )}
                    </div>

                    <div className="booking-section">
                      <p className="hint">
                        <strong>Benötigte Werkzeuge (mindestens eins)</strong>
                      </p>
                      {selectedWorkshop.tools.length > 0 ? (
                        <>
                          <div className="row" style={{ marginBottom: "0.5rem" }}>
                            <button
                              type="button"
                              className="btn secondary"
                              onClick={() =>
                                setSelectedToolIdsByWorkshop((prev) => ({
                                  ...prev,
                                  [selectedWorkshop.workshop.id]: selectedWorkshop.tools
                                    .filter((tool) => tool.selectable)
                                    .map((tool) => tool.id)
                                }))
                              }
                            >
                              Alle auswählen
                            </button>
                            <button
                              type="button"
                              className="btn ghost"
                              onClick={() =>
                                setSelectedToolIdsByWorkshop((prev) => ({
                                  ...prev,
                                  [selectedWorkshop.workshop.id]: []
                                }))
                              }
                            >
                              Auswahl löschen
                            </button>
                          </div>
                          <div className="workshop-booking-tools">
                            {selectedWorkshop.tools.map((tool) => {
                              const selectedToolIds = selectedToolIdsByWorkshop[selectedWorkshop.workshop.id] ?? [];
                              const checked = selectedToolIds.includes(tool.id);
                              return (
                                <label key={tool.id} className="workshop-booking-tool-option">
                                  <input
                                    type="checkbox"
                                    checked={checked}
                                    disabled={!token || !tool.selectable}
                                    onChange={(event) =>
                                      setSelectedToolIdsByWorkshop((prev) => {
                                        const current = prev[selectedWorkshop.workshop.id] ?? [];
                                        const next = event.target.checked
                                          ? Array.from(new Set([...current, tool.id]))
                                          : current.filter((id) => id !== tool.id);
                                        return {
                                          ...prev,
                                          [selectedWorkshop.workshop.id]: next
                                        };
                                      })
                                    }
                                  />
                                  <span>{tool.name}</span>
                                  <small>{toolCategoryByValue.get(tool.category)?.label ?? tool.category}</small>
                                </label>
                              );
                            })}
                          </div>
                        </>
                      ) : (
                        <p className="hint">Für diese Werkstatt wurde noch keine Ausstattung hinterlegt.</p>
                      )}
                    </div>

                    <button
                      type="button"
                      className="booking-button"
                      onClick={() => void bookWorkshop(selectedWorkshop.workshop.id)}
                      disabled={!selectedWorkshopHasAvailableSlots}
                    >
                      {token ? "Buchen" : "Login"}
                    </button>
                    <p className="booking-hint">
                      {selectedWorkshopHasAvailableSlots
                        ? "Der Anbieter muss deine Anfrage noch bestätigen."
                        : "Aktuell ist kein verfügbares Zeitfenster hinterlegt."}
                    </p>
                  </div>
                )}

                {selectedWorkshop.slots.length > 0 ? (
                  <ul className="meta-list">
                    {selectedWorkshop.slots.map((slot) => (
                      <li key={slot.id} className="slot-item">
                        <div>
                          <strong>{formatWorkshopDate(slot.startIso)}</strong>
                          <span> bis </span>
                          <strong>{formatWorkshopDate(slot.endIso)}</strong>
                          {slot.blockedByOwner && <span className="slot-badge">blockiert</span>}
                        </div>
                      </li>
                    ))}
                  </ul>
                ) : (
                  <p className="hint">Keine Zeitfenster hinterlegt.</p>
                )}
              </div>
            </div>

            {currentUser && selectedWorkshop.workshop.ownerId === currentUser.id && (
              <div className="workshop-modal-footer">
                <Link className="btn secondary" to={`/workshops/${selectedWorkshop.workshop.id}/edit`} onClick={closeWorkshop}>
                  Werkstatt bearbeiten
                </Link>
                <Link className="btn" to="/workshops/availability" onClick={closeWorkshop}>
                  Verfügbarkeit verwalten
                </Link>
              </div>
            )}
          </div>
        </div>
      )}
    </section>
  );
}
